const rz = await r.json();
check("wniosek o rezerwację", r.status === 200 && rz.id, JSON.stringify(rz));
r = await req(`/api/admin/rezerwacje/${rz.id}`, { c: J, method: "POST", body: { decyzja: "zatwierdz" } });
check("użytkownik nie zatwierdza → 403", r.status === 403);
r = await req(`/api/admin/rezerwacje/${rz.id}`, { c: A, method: "POST", body: { decyzja: "zatwierdz" } });
check("admin zatwierdza", r.status === 200);
r = await req("/api/rezerwacje", { c: A, method: "POST", body: { od, do: doo, kody: [101] } });
check("wniosek na zajęty czas → 409", r.status === 409);
r = await req("/api/admin/uzytkownicy/" + jan.oid, { c: A, method: "PATCH", body: { akcja: "zablokuj", powod: "test" } });
check("admin blokuje konto", r.status === 200);
r = await req("/api/me", { c: J });
check("zablokowane konto → 403 od razu", r.status === 403);
const audit = await owner`select zdarzenie, wynik from audyt order by id`;
check("audyt: csrf, limit, brak_uprawnien, blokada", ["csrf", "limit", "brak_uprawnien", "admin_osoba_zablokuj"].every((z) => audit.some((a) => a.zdarzenie === z)), JSON.stringify(audit.map((a) => a.zdarzenie)));
await owner.end();
